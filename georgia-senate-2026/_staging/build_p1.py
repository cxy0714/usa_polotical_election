"""Build all CSV datasets for georgia-senate-2026 from verified sources."""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
CASE = os.path.dirname(HERE)
SRC = {r['source_id']: r['url'] for r in csv.DictReader(open(os.path.join(CASE, '09_sources', 'sources.csv'), encoding='utf-8'))}


def s(*ids):
    # contract: exactly one SRC-####|url per cell; the first id is the primary source
    return '%s|%s' % (ids[0], SRC[ids[0]])


def W(rel, header, rows):
    p = os.path.join(CASE, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f, lineterminator='\n', quoting=csv.QUOTE_MINIMAL)
        w.writerow(header)
        for r in rows:
            assert len(r) == len(header), (rel, len(r), len(header), r[:2])
            w.writerow(r)
    print('%-46s %3d rows' % (rel, len(rows)))


