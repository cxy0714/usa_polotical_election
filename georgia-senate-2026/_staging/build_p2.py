fixed = []
for r in E:
    if len(r) == len(H) + 1:
        # one stray 'unknown' slipped into the message/notes block; drop the last one there
        for i in range(len(H) - 1, 15, -1):
            if r[i] == 'unknown':
                del r[i]
                fixed.append(r[0])
                break
