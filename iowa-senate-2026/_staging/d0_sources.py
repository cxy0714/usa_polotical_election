def clean_title(t):
    t = re.sub(r"&#\d+;|&amp;|&quot;|&#x27;", "", t)
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"\s*[\|\u2022]\s*(Iowa Capital Dispatch|thegazette\.com|KCCI|KCRG.*|FOX.*|Newsweek|PBS NewsHour).*$", "", t)
    return t[:170]


