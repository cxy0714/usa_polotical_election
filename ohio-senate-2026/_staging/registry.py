def publisher_for(url):
    host = url.split("://", 1)[1].split("/")[0].lower().replace("www.", "")
    if host in PUBLISHERS:
        return PUBLISHERS[host]
    parts = host.split(".")
    for i in range(len(parts) - 1):
        cand = ".".join(parts[i:])
        if cand in PUBLISHERS:
            return PUBLISHERS[cand]
    return host


def pubdate(key):
    d = TITLES.get(key, {}).get("pubdate", "")
    if len(d) >= 10 and d[4] == "-" and d[7] == "-":
        return d[:10]
    return "unknown"


def title(key, fallback="unknown"):
    t = TITLES.get(key, {}).get("title", "")
    t = t.split(" | ")[0].strip() if t.count(" | ") and len(t) > 60 else t
    return t or fallback


